//! Interactive practice: Nova answers a lesson's practice questions herself, the teacher marks
//! each answer and may write a correction and a note, and an approved training pass learns from
//! the marked answers through the ordinary teaching session (its acceptance rules and held-out
//! checks), with the lesson's held-out questions scored before and after.
//!
//! What each training target is stays recorded: an answer the teacher marked right is trained
//! as Nova wrote it ("Nova's answer, confirmed"), a wrong answer with a correction is trained on
//! the teacher's correction ("teacher's correction"), and a wrong answer without one on the
//! lesson's own answer when it has one ("lesson answer"); otherwise it is not trained. Nothing
//! is trained until the teacher has marked it.
use super::eval::{reply, reply_budget, MAX_REPLY_TOKENS};
use super::lessons::{chat_prompt, qa, Item, Kind};
use super::session::{teach_with, Event, SessionConfig, SessionResult};
use crate::memory::{MemoryStore, RETRIEVE};
use crate::model::{Ablation, Bicameral};
use serde::{Deserialize, Serialize};
use std::sync::atomic::AtomicBool;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Mark {
    Right,
    Wrong,
}

/// Where a training target came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TargetOrigin {
    /// Nova's own answer, marked right by the teacher.
    NovaConfirmed,
    /// The teacher's correction of a wrong answer.
    TeacherCorrection,
    /// The lesson's answer for a wrong answer without a correction.
    LessonAnswer,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PracticeItem {
    pub question: String,
    /// The lesson's answer, if it has one (shown to the teacher; never shown to Nova).
    #[serde(default)]
    pub expected: Option<String>,
    /// Nova's answer, generated by the network.
    #[serde(default)]
    pub answer: String,
    /// Study Mode memories in front of the question when she answered.
    #[serde(default)]
    pub memories: Vec<String>,
    #[serde(default)]
    pub mark: Option<Mark>,
    #[serde(default)]
    pub correction: String,
    /// Teacher note (never trained on).
    #[serde(default)]
    pub note: String,
    /// What was trained for this item, if anything.
    #[serde(default)]
    pub target: Option<(String, TargetOrigin)>,
    /// Nova's answer to the same question after the training pass.
    #[serde(default)]
    pub after: Option<String>,
    /// The teacher's grade, 0-100 (partial credit). 100 goes with "right"; anything lower is
    /// never trained as Nova wrote it.
    #[serde(default)]
    pub grade: Option<f32>,
    /// The automatic grade (a suggestion from the lesson's answer, when it has one).
    #[serde(default)]
    pub auto: Option<super::reward::Grade>,
}

/// The prompt for a practice question, with Study Mode memories in front when a store is given.
fn prompt(
    model: &Bicameral,
    question: &str,
    memory: Option<&mut MemoryStore>,
    now: u64,
) -> (String, Vec<String>) {
    let Some(store) = memory else { return (chat_prompt(question), Vec::new()) };
    let ids: Vec<u64> = store.retrieve(question, RETRIEVE).into_iter().map(|(id, _)| id).collect();
    let ctx = store.context(&ids, model.config.max_tokens / 2);
    let texts = ids.iter().filter_map(|id| store.get(*id).map(|m| m.text.clone())).collect();
    store.record("practice", question, &ids, now);
    (format!("{ctx}{}", chat_prompt(question)), texts)
}

/// Nova answers every question herself (greedy replies from the network).
pub fn answer_all(
    model: &Bicameral,
    items: &mut [PracticeItem],
    mut memory: Option<&mut MemoryStore>,
    after: bool,
    now: u64,
) -> Result<(), String> {
    for it in items.iter_mut() {
        let (p, mems) = prompt(model, &it.question, memory.as_deref_mut(), now);
        // Room for the expected answer when there is one (see `eval::reply_budget`).
        let limit = it.expected.as_deref().map_or(MAX_REPLY_TOKENS, |e| reply_budget(e, true));
        let r = reply(model, &p, limit, Ablation::default())?;
        if after {
            it.after = Some(r);
        } else {
            it.answer = r;
            it.memories = mems;
        }
    }
    Ok(())
}

/// The training target of a marked item and where it comes from (None: not trained).
pub fn target(it: &PracticeItem) -> Option<(String, TargetOrigin)> {
    let clean = |s: &str| s.split_whitespace().collect::<Vec<_>>().join(" ");
    // A partly right answer (grade below 100) is never trained as written.
    let mark = match (it.mark?, it.grade) {
        (Mark::Right, Some(g)) if g < 100. => Mark::Wrong,
        (m, _) => m,
    };
    match mark {
        Mark::Right if !it.answer.trim().is_empty() => Some((clean(&it.answer), TargetOrigin::NovaConfirmed)),
        Mark::Right => None,
        Mark::Wrong if !it.correction.trim().is_empty() => {
            Some((clean(&it.correction), TargetOrigin::TeacherCorrection))
        }
        Mark::Wrong => it
            .expected
            .as_deref()
            .map(|e| e.split('|').next().unwrap_or(e))
            .filter(|e| !e.trim().is_empty())
            .map(|e| (clean(e), TargetOrigin::LessonAnswer)),
    }
}

/// Fills in the automatic grade of each answer (from the lesson's answer; uncertain without one).
pub fn auto_grade(items: &mut [PracticeItem]) {
    for it in items.iter_mut() {
        it.auto = Some(match it.expected.as_deref().filter(|e| !e.trim().is_empty()) {
            Some(e) => {
                let key = super::grading::AnswerKey::parse(e, super::grading::GradeMode::Sentence)
                    .filter(|k| k.accepted.len() > 1 || !k.must.is_empty());
                let first = e.split('|').next().unwrap_or(e).trim();
                super::reward::grade_reply(first, key.as_ref(), None, &it.answer, false)
            }
            None => {
                super::reward::Grade::uncertain("no lesson answer to compare with: the teacher grades it")
            }
        });
    }
}

/// Marks every answer whose automatic grade is certain (right at 100%, wrong at 0%), leaving
/// partial and uncertain ones to the teacher. Returns how many were marked.
pub fn accept_auto_grades(items: &mut [PracticeItem]) -> usize {
    let mut n = 0;
    for it in items.iter_mut().filter(|i| i.mark.is_none()) {
        let Some(g) = &it.auto else { continue };
        match g.percent {
            Some(p) if g.correct => {
                it.mark = Some(Mark::Right);
                it.grade = Some(p);
            }
            Some(p) if p <= 0. => {
                it.mark = Some(Mark::Wrong);
                it.grade = Some(0.);
            }
            _ => continue,
        }
        n += 1;
    }
    n
}

/// The question as a lesson unit (for the reward ledger), answered with memories in front when
/// it was.
fn as_item(it: &PracticeItem, source: &str) -> Item {
    let expected = it.expected.as_deref().map(|e| e.split('|').next().unwrap_or(e).trim().to_string());
    Item {
        kind: Kind::Dialogue,
        source: source.to_string(),
        held_out: false,
        segments: qa(&it.question, expected.as_deref().unwrap_or("")),
        prompt: Some(it.question.clone()),
        answer: expected,
        contradicted: None,
        users: Vec::new(),
        replies: Vec::new(),
        key: None,
        reading: None,
        context: (!it.memories.is_empty()).then(|| {
            it.memories.iter().map(|m| format!("{}{m}\n", crate::memory::MEMORY)).collect::<String>()
        }),
        spelling: false,
    }
}

/// Records the teacher's grades and notes in the reward ledger (marked items only; a mark without
/// a percentage counts as 100 or 0). Returns how many were recorded.
pub fn record_grades(
    rewards: &mut super::reward::Rewards,
    items: &[PracticeItem],
    source: &str,
    step: u64,
) -> usize {
    use super::reward::{Answer, Evidence, Origin};
    let mut n = 0;
    for it in items {
        let Some(mark) = it.mark else { continue };
        let percent = it.grade.unwrap_or(if mark == Mark::Right { 100. } else { 0. });
        let unit = as_item(it, source);
        let recorded = rewards.record(Evidence {
            item: &unit,
            answer: Answer::Reply(&it.answer),
            origin: Origin::Practice,
            step,
            checkpoint: false,
            teacher: Some((percent, &it.note)),
        });
        n += usize::from(recorded.is_some());
    }
    n
}

/// Training units from the marked items.
pub fn training_items(items: &mut [PracticeItem], source: &str) -> Vec<Item> {
    let mut out = Vec::new();
    for it in items.iter_mut() {
        it.target = target(it);
        if let Some((t, _)) = &it.target {
            let mut item = Item {
                kind: Kind::Dialogue,
                source: source.to_string(),
                held_out: false,
                segments: qa(&it.question, t),
                prompt: Some(it.question.clone()),
                answer: Some(t.clone()),
                contradicted: None,
                users: Vec::new(),
                replies: Vec::new(),
                key: None,
                reading: None,
                context: None,
                spelling: false,
            };
            item.held_out = false;
            out.push(item);
        }
    }
    out
}

/// The training pass: a teaching session on the marked answers, judged on the lesson's held-out
/// questions (`lesson` holds them; its taught units are not trained here). Returns None when no
/// item is marked for training.
pub fn train(
    model: &Bicameral,
    items: &mut [PracticeItem],
    lesson: &[Item],
    archive: &[Item],
    cfg: &SessionConfig,
    observer: &mut dyn FnMut(&Event),
    stop: &AtomicBool,
) -> Result<Option<SessionResult>, String> {
    let source = lesson.first().map(|i| i.source.clone()).unwrap_or_else(|| "practice".into());
    let practice = training_items(items, &source);
    if practice.is_empty() {
        return Ok(None);
    }
    teach_with(model, lesson, Some(&practice), archive, cfg, observer, stop).map(Some)
}

/// [`train`] with rewards: the teacher's grades are recorded first, and with reward-guided
/// training on, answers graded low are practised more (the targets stay the teacher's
/// corrections, the lesson's answers, or answers the teacher marked fully right).
#[allow(clippy::too_many_arguments)]
pub fn train_rewarded(
    model: &Bicameral,
    items: &mut [PracticeItem],
    lesson: &[Item],
    archive: &[Item],
    cfg: &SessionConfig,
    mut rewards: Option<&mut super::reward::Rewards>,
    observer: &mut dyn FnMut(&Event),
    stop: &AtomicBool,
) -> Result<Option<SessionResult>, String> {
    let source = lesson.first().map(|i| i.source.clone()).unwrap_or_else(|| "practice".into());
    if let Some(r) = rewards.as_deref_mut() {
        record_grades(r, items, &source, model.step);
    }
    let practice = training_items(items, &source);
    if practice.is_empty() {
        return Ok(None);
    }
    super::session::teach_rewarded(model, lesson, Some(&practice), archive, cfg, rewards, observer, stop)
        .map(Some)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn item(answer: &str, mark: Option<Mark>, correction: &str, expected: Option<&str>) -> PracticeItem {
        PracticeItem {
            question: "Is Max a dog?".into(),
            expected: expected.map(String::from),
            answer: answer.into(),
            memories: vec![],
            mark,
            correction: correction.into(),
            note: String::new(),
            target: None,
            after: None,
            grade: None,
            auto: None,
        }
    }

    #[test]
    fn targets_keep_their_origin() {
        assert_eq!(
            target(&item("Yes.", Some(Mark::Right), "", None)),
            Some(("Yes.".into(), TargetOrigin::NovaConfirmed))
        );
        assert_eq!(
            target(&item("No.", Some(Mark::Wrong), "Yes, Max is a dog.", Some("Yes."))),
            Some(("Yes, Max is a dog.".into(), TargetOrigin::TeacherCorrection))
        );
        assert_eq!(
            target(&item("No.", Some(Mark::Wrong), "", Some("Yes. | must: yes"))),
            Some(("Yes.".into(), TargetOrigin::LessonAnswer))
        );
        assert_eq!(target(&item("No.", Some(Mark::Wrong), "", None)), None);
        assert_eq!(target(&item("Yes.", None, "", Some("Yes."))), None, "unmarked items are never trained");
        let mut partly = item("Max dog", Some(Mark::Right), "", Some("Yes, Max is a dog."));
        partly.grade = Some(60.);
        assert_eq!(
            target(&partly),
            Some(("Yes, Max is a dog.".into(), TargetOrigin::LessonAnswer)),
            "a partly right answer is never trained as written"
        );
    }
}
