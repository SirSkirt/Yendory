//! Thinking tree: a recorded account of how the model produced a reply, token by token.
//!
//! Nova-2 has no explicit reasoning steps. For every token it reads, the lower stage runs once
//! and the upper stage runs `loops` times ("thinking rounds"), exchanging signals with the dense
//! hemisphere before each round. The tree shows only what that computation actually produced:
//! the token chosen at each step and the alternatives it weighed (real probabilities), what the
//! left state would have output after the lower stage and after each round (read-outs), the
//! gate openings, how much the dense hemisphere changed the decision, which earlier tokens the
//! last block attended to, and, for the closest calls, where the runner-up would have led
//! (generated by the same model). Nothing is invented or summarised by rules.
use super::measure::{probabilities, total_variation};
use super::{Ablation, Bicameral, KvCache};
use crate::tokenizer::TokenId;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Choice {
    pub token: String,
    pub id: TokenId,
    pub probability: f32,
}

/// What the model would have predicted if it had stopped at this point of the forward pass.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Readout {
    /// "lower stage", "round 1", … The last one is the model's actual output.
    pub stage: String,
    pub top: Vec<Choice>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ThoughtStep {
    pub index: usize,
    pub chosen: Choice,
    /// The next most likely tokens at this step (not chosen).
    pub alternatives: Vec<Choice>,
    /// Uncertainty of the decision, in bits (0 = certain).
    pub entropy: f32,
    pub readouts: Vec<Readout>,
    /// Mean gate opening of each right→left exchange (exchange 1, then each round).
    pub gate_means: Vec<f32>,
    /// Total-variation change of this step's distribution when the right hemisphere's input is
    /// cut (0 = no influence, 1 = a completely different decision).
    pub right_influence: f32,
    /// The earlier tokens the last block attended to most (mean over heads).
    pub attended: Vec<(String, f32)>,
}

/// A path not taken: the runner-up token at a close step, continued greedily by the model.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Branch {
    pub at_step: usize,
    pub first: Choice,
    pub continuation: Vec<Choice>,
    pub text: String,
    /// The branch reached the end of a reply (a newline) within the depth limit.
    pub ended: bool,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ThinkingTree {
    pub step: u64,
    pub prompt: String,
    pub prompt_ids: Vec<TokenId>,
    /// Token ids of the reply, as generated.
    pub path_ids: Vec<TokenId>,
    pub reply: String,
    pub rounds: usize,
    pub steps: Vec<ThoughtStep>,
    pub branches: Vec<Branch>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct ThinkOptions {
    pub max_tokens: usize,
    pub alternatives: usize,
    pub max_branches: usize,
    pub branch_tokens: usize,
    /// Only runner-ups at least this likely become branches.
    pub min_branch_probability: f32,
}
impl Default for ThinkOptions {
    fn default() -> Self {
        Self {
            max_tokens: 48,
            alternatives: 4,
            max_branches: 3,
            branch_tokens: 12,
            min_branch_probability: 0.05,
        }
    }
}

fn ranked(p: &[f64]) -> Vec<(usize, f64)> {
    let mut r: Vec<(usize, f64)> = p.iter().copied().enumerate().collect();
    // Stable sort: equal probabilities keep id order.
    r.sort_by(|a, b| b.1.total_cmp(&a.1));
    r
}

/// The greedy choice exactly as `generate_cached_ids` makes it (same probabilities, the last
/// maximum wins ties), so the recorded reply is the reply the model gives.
fn greedy(model: &Bicameral, logits: &[f32]) -> usize {
    let p = model.next_token_probabilities(logits.to_vec());
    p.iter().enumerate().max_by(|a, b| a.1.total_cmp(b.1)).map(|x| x.0).unwrap_or(0)
}

impl Bicameral {
    fn choice(&self, id: usize, p: f64) -> Choice {
        Choice { token: self.tokenizer.token_label(id as TokenId), id: id as TokenId, probability: p as f32 }
    }

    /// Generates a greedy reply to `prompt` and records how each token was decided.
    pub fn think(&self, prompt: &str, opt: &ThinkOptions) -> Result<ThinkingTree, String> {
        let ids = self.tokenizer.encode(prompt)?;
        if ids.is_empty() {
            return Err("Empty prompt".into());
        }
        let mut cache = KvCache::with_trace(self, Ablation::default());
        let mut silenced = KvCache::new(self, Ablation { no_afferent: true, ..Ablation::default() });
        let mut logits = cache.prefill(self, &ids)?;
        let mut logits_silenced = silenced.prefill(self, &ids)?;
        let mut context = ids.clone();
        let mut path = Vec::new();
        let mut steps = Vec::new();
        let rounds = self.config.loops;
        for index in 0..opt.max_tokens {
            let p = probabilities(self, &logits);
            let trace = cache.trace().cloned().unwrap_or_default();
            let next = greedy(self, &logits);
            let order = ranked(&p);
            let readouts = trace
                .readouts
                .iter()
                .enumerate()
                .map(|(i, z)| Readout {
                    stage: if i == 0 {
                        "lower stage".into()
                    } else if i == rounds {
                        format!("round {i} (output)")
                    } else {
                        format!("round {i}")
                    },
                    top: ranked(&probabilities(self, z))
                        .iter()
                        .take(3)
                        .map(|&(t, q)| self.choice(t, q))
                        .collect(),
                })
                .collect();
            let attended = trace
                .stages
                .last()
                .map(|s| {
                    let n = s.attention.first().map_or(0, |h| h.len());
                    let window = &context[context.len() - n.min(context.len())..];
                    let mut mean: Vec<(usize, f32)> = (0..n)
                        .map(|t| {
                            (t, s.attention.iter().map(|h| h[t]).sum::<f32>() / s.attention.len() as f32)
                        })
                        .collect();
                    mean.sort_by(|a, b| b.1.total_cmp(&a.1));
                    mean.iter()
                        .take(3)
                        .filter_map(|&(t, w)| window.get(t).map(|&id| (self.tokenizer.token_label(id), w)))
                        .collect()
                })
                .unwrap_or_default();
            steps.push(ThoughtStep {
                index,
                chosen: self.choice(next, p[next]),
                alternatives: order
                    .iter()
                    .filter(|&&(t, _)| t != next)
                    .take(opt.alternatives)
                    .map(|&(t, q)| self.choice(t, q))
                    .collect(),
                entropy: -p.iter().filter(|&&q| q > 0.).map(|&q| q * q.log2()).sum::<f64>() as f32,
                readouts,
                gate_means: trace
                    .gates
                    .iter()
                    .map(|g| g.gate.iter().sum::<f32>() / g.gate.len().max(1) as f32)
                    .collect(),
                right_influence: total_variation(&p, &probabilities(self, &logits_silenced)),
                attended,
            });
            let token = next as TokenId;
            path.push(token);
            context.push(token);
            if token == b'\n' as TokenId {
                break;
            }
            logits = cache.append(self, token)?;
            logits_silenced = silenced.append(self, token)?;
        }
        let reply = self.tokenizer.decode(&path)?.trim_end_matches('\n').to_string();

        // Branches at the closest calls: where the runner-up came nearest to the chosen token.
        let mut close: Vec<&ThoughtStep> = steps
            .iter()
            .filter(|s| s.alternatives.first().is_some_and(|a| a.probability >= opt.min_branch_probability))
            .collect();
        close.sort_by(|a, b| {
            let r = |s: &ThoughtStep| s.alternatives[0].probability / s.chosen.probability.max(1e-9);
            r(b).total_cmp(&r(a))
        });
        let mut branches = Vec::new();
        for s in close.into_iter().take(opt.max_branches) {
            let first = s.alternatives[0].clone();
            let mut prefix = ids.clone();
            prefix.extend_from_slice(&path[..s.index]);
            prefix.push(first.id);
            let mut c = KvCache::new(self, Ablation::default());
            let mut z = c.prefill(self, &prefix)?;
            let mut continuation = Vec::new();
            let mut ended = first.id == b'\n' as TokenId;
            while !ended && continuation.len() < opt.branch_tokens {
                let p = probabilities(self, &z);
                let t = greedy(self, &z);
                continuation.push(self.choice(t, p[t]));
                ended = t == b'\n' as usize;
                if !ended {
                    z = c.append(self, t as TokenId)?;
                }
            }
            let ids: Vec<TokenId> =
                std::iter::once(first.id).chain(continuation.iter().map(|c| c.id)).collect();
            branches.push(Branch {
                at_step: s.index,
                text: self.tokenizer.decode(&ids)?.trim_end_matches('\n').to_string(),
                first,
                continuation,
                ended,
            });
        }
        branches.sort_by_key(|b| b.at_step);
        Ok(ThinkingTree {
            step: self.step,
            prompt: prompt.to_string(),
            prompt_ids: ids,
            path_ids: path,
            reply,
            rounds,
            steps,
            branches,
        })
    }
}
